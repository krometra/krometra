// Разрешение конкуренции «хелпер базовой плоскости против грани тела».
//
// Хелперы базовых плоскостей — квадраты max(габарит)×1.4: они накрывают деталь
// целиком, а XZ/YZ ещё и проходят сквозь неё. Сравнение расстояний «в лоб»
// отдавало им клик по грани тела (для грани, компланарной хелперу, выбор решала
// погрешность float), и эскиз молча создавался без привязки к телу.
//
// Правило: попали в видимое тело — выигрывает тело. Хелпер берёт клик только
// мимо тела, а места там всегда хватает — он на 40% больше габарита детали.

export function planeHelperWins(planeDistance: number | null, meshDistance: number | null): boolean {
  if (planeDistance === null || !Number.isFinite(planeDistance)) return false;
  return meshDistance === null || !Number.isFinite(meshDistance);
}
